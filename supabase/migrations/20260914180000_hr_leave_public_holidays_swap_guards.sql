-- The AD date of a BS day, or NULL outside the table or past the month's length.
CREATE OR REPLACE FUNCTION public.bs_to_ad(p_bs_year int, p_bs_month int, p_bs_day int)
RETURNS date
LANGUAGE sql
STABLE
SET search_path TO 'public'
AS $$
  SELECT m.ad_start + (p_bs_day - 1)
    FROM bs_months m
   WHERE m.bs_year = p_bs_year AND m.bs_month = p_bs_month
     AND p_bs_day BETWEEN 1 AND m.days
$$;
REVOKE ALL ON FUNCTION public.bs_to_ad(int, int, int) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.bs_to_ad(int, int, int) TO authenticated, service_role;

-- The number of distinct PUBLIC holiday dates a client has inside an AD range. SECURITY DEFINER
-- with its caller checked, so the count cannot come back 0 for a caller whose RLS view of the
-- calendar is narrower — the S749 vacuous-EXISTS lesson. The Self-Service submit runs as the
-- function owner and reaches it that way.
CREATE OR REPLACE FUNCTION public.hr_public_holiday_count(p_client_id uuid, p_start date, p_end date)
RETURNS int
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $$
  SELECT count(DISTINCT m.ad_start + (h.bs_day - 1))::int
    FROM hr_holiday_calendar h
    JOIN bs_months m ON m.bs_year = h.bs_year AND m.bs_month = h.bs_month AND h.bs_day BETWEEN 1 AND m.days
   WHERE h.client_id = p_client_id
     AND h.holiday_type = 'public'
     AND h.removed_at IS NULL
     AND m.ad_start + (h.bs_day - 1) BETWEEN p_start AND p_end
     -- No `current_user` escape here: inside SECURITY DEFINER it is always the owner, so it would
     -- pass every caller. A session with no profile (the migration's own recount below, a service
     -- job) gets 0 — which is why the recount does not call this function.
     AND COALESCE(public.is_admin() OR p_client_id = public.my_client_id(), false)
$$;
REVOKE ALL ON FUNCTION public.hr_public_holiday_count(uuid, date, date) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.hr_public_holiday_count(uuid, date, date) TO authenticated, service_role;

-- The S749 validate trigger, with public holidays taken out of the count.
CREATE OR REPLACE FUNCTION public.hr_leave_requests_validate()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $$
DECLARE
  v_clash    hr_leave_requests;
  v_calendar int;
  v_holidays int;
BEGIN
  IF NEW.start_date IS NULL OR NEW.end_date IS NULL OR NEW.end_date < NEW.start_date THEN
    RAISE EXCEPTION 'leave_dates_invalid: the end date is before the start date';
  END IF;
  IF COALESCE(NEW.day_type, 'full') <> 'full' AND NEW.end_date <> NEW.start_date THEN
    RAISE EXCEPTION 'leave_half_day_range: a half-day request covers one day';
  END IF;
  v_calendar := NEW.end_date - NEW.start_date + 1;
  IF v_calendar > 366 THEN
    RAISE EXCEPTION 'leave_range_too_long: a leave request covers at most a year';
  END IF;

  -- Public holidays inside the range are not charged (decided 2026-09-14). Only a request that is
  -- still open or approved is recounted and refused; a decided one keeps the figure it was decided on.
  IF NEW.status IN ('pending', 'approved') THEN
    v_holidays := public.hr_public_holiday_count(NEW.client_id, NEW.start_date, NEW.end_date);
    IF v_holidays >= v_calendar THEN
      RAISE EXCEPTION 'leave_all_holidays: every day in this request is a public holiday';
    END IF;
    NEW.days := CASE WHEN COALESCE(NEW.day_type, 'full') <> 'full' THEN 0.5
                     ELSE v_calendar - v_holidays END;
  ELSIF TG_OP = 'INSERT' THEN
    NEW.days := CASE WHEN COALESCE(NEW.day_type, 'full') <> 'full' THEN 0.5 ELSE v_calendar END;
  END IF;

  IF NEW.status IN ('pending', 'approved')
     AND NOT COALESCE(public.is_admin(), false) THEN
    PERFORM pg_advisory_xact_lock(hashtext('hr_leave_requests:' || NEW.employee_id::text));
    SELECT * INTO v_clash FROM hr_leave_requests o
     WHERE o.employee_id = NEW.employee_id
       AND o.id <> NEW.id
       AND o.status IN ('pending', 'approved')
       AND o.start_date <= NEW.end_date AND NEW.start_date <= o.end_date
     LIMIT 1;
    IF FOUND THEN
      RAISE EXCEPTION 'leave_overlap: overlaps a % request from % to %', v_clash.status, v_clash.start_date, v_clash.end_date;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

-- Recount the open and approved requests already stored. A plain UPDATE of `days` does not fire
-- the trigger (it listens to the date, type, status and employee columns), so the figure is set
-- here directly, and only where it moves. The holiday count is inline, not the function: a
-- migration session has no profile, so the function's caller check would count nothing.
WITH counted AS (
  SELECT r.id,
         GREATEST(0, (r.end_date - r.start_date + 1) - (
           SELECT count(DISTINCT m.ad_start + (h.bs_day - 1))
             FROM hr_holiday_calendar h
             JOIN bs_months m ON m.bs_year = h.bs_year AND m.bs_month = h.bs_month AND h.bs_day BETWEEN 1 AND m.days
            WHERE h.client_id = r.client_id AND h.holiday_type = 'public' AND h.removed_at IS NULL
              AND m.ad_start + (h.bs_day - 1) BETWEEN r.start_date AND r.end_date)) AS days
    FROM hr_leave_requests r
   WHERE r.status IN ('pending', 'approved') AND COALESCE(r.day_type, 'full') = 'full'
)
UPDATE public.hr_leave_requests r
   SET days = c.days
  FROM counted c
 WHERE c.id = r.id AND r.days IS DISTINCT FROM c.days;

-- ── (3) request_shift_swap: past, unpublished and already-requested days are refused ─────────
CREATE OR REPLACE FUNCTION public.request_shift_swap(p_target_employee_id uuid, p_bs_year integer, p_bs_month integer, p_my_bs_day integer, p_target_bs_day integer, p_note text)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_client_id uuid;
  v_employee_id uuid;
  v_my_shift uuid;
  v_target_shift uuid;
  v_today date := (now() AT TIME ZONE 'Asia/Kathmandu')::date;
  v_id uuid;
BEGIN
  SELECT client_id, hr_employee_id INTO v_client_id, v_employee_id
  FROM profiles WHERE id = auth.uid() AND hr_self_service = true;
  IF v_employee_id IS NULL THEN RAISE EXCEPTION 'not authorized'; END IF;
  IF p_target_employee_id = v_employee_id THEN RAISE EXCEPTION 'cannot swap with yourself'; END IF;

  IF NOT EXISTS (SELECT 1 FROM hr_employees WHERE id = p_target_employee_id AND client_id = v_client_id) THEN
    RAISE EXCEPTION 'coworker not found';
  END IF;

  -- A day already gone cannot be swapped. NULL (outside the calendar table) is refused too.
  IF COALESCE(public.bs_to_ad(p_bs_year, p_bs_month, p_my_bs_day) < v_today, true)
     OR COALESCE(public.bs_to_ad(p_bs_year, p_bs_month, p_target_bs_day) < v_today, true) THEN
    RAISE EXCEPTION 'swap_day_past: one of those days has already gone';
  END IF;

  -- Only published days: an employee must not be able to discover or trade a draft roster.
  IF NOT EXISTS (SELECT 1 FROM hr_roster_publish_state WHERE client_id = v_client_id
                   AND bs_year = p_bs_year AND bs_month = p_bs_month AND bs_day = p_my_bs_day)
     OR NOT EXISTS (SELECT 1 FROM hr_roster_publish_state WHERE client_id = v_client_id
                   AND bs_year = p_bs_year AND bs_month = p_bs_month AND bs_day = p_target_bs_day) THEN
    RAISE EXCEPTION 'swap_day_unpublished: that day''s roster has not been published';
  END IF;

  SELECT shift_type_id INTO v_my_shift FROM hr_roster
    WHERE client_id = v_client_id AND employee_id = v_employee_id
      AND bs_year = p_bs_year AND bs_month = p_bs_month AND bs_day = p_my_bs_day;
  IF v_my_shift IS NULL THEN RAISE EXCEPTION 'you have no shift on that day'; END IF;

  SELECT shift_type_id INTO v_target_shift FROM hr_roster
    WHERE client_id = v_client_id AND employee_id = p_target_employee_id
      AND bs_year = p_bs_year AND bs_month = p_bs_month AND bs_day = p_target_bs_day;
  IF v_target_shift IS NULL THEN RAISE EXCEPTION 'coworker has no shift on that day'; END IF;

  -- One open request per shift: a second one for a day already being traded could be approved
  -- after the first had moved the shift, and approve_shift_swap would then refuse it anyway.
  IF EXISTS (
    SELECT 1 FROM hr_shift_swap_requests s
     WHERE s.client_id = v_client_id AND s.bs_year = p_bs_year AND s.bs_month = p_bs_month
       AND s.status IN ('pending_target', 'pending_admin')
       AND ((s.requester_employee_id = v_employee_id AND s.requester_bs_day = p_my_bs_day)
         OR (s.target_employee_id = v_employee_id AND s.target_bs_day = p_my_bs_day)
         OR (s.requester_employee_id = p_target_employee_id AND s.requester_bs_day = p_target_bs_day)
         OR (s.target_employee_id = p_target_employee_id AND s.target_bs_day = p_target_bs_day))
  ) THEN
    RAISE EXCEPTION 'swap_already_requested: one of those shifts already has a swap waiting';
  END IF;

  INSERT INTO hr_shift_swap_requests (
    client_id, requester_employee_id, target_employee_id, bs_year, bs_month,
    requester_bs_day, target_bs_day, requester_shift_type_id, target_shift_type_id, note, status
  ) VALUES (
    v_client_id, v_employee_id, p_target_employee_id, p_bs_year, p_bs_month,
    p_my_bs_day, p_target_bs_day, v_my_shift, v_target_shift, left(coalesce(p_note, ''), 500), 'pending_target'
  ) RETURNING id INTO v_id;

  RETURN v_id;
END;
$function$;

