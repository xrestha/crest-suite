-- S749b — Public holidays inside a leave are not charged, and a swap request is checked.
--
-- (1) The database learns the Bikram Sambat calendar. Holidays, the roster and attendance are all
--     stored in BS; leave requests are stored as AD dates. Until now every BS↔AD conversion lived in
--     src/utils/bsCalendar.js, so no trigger could ask "is this AD date a public holiday?". `bs_months`
--     is that file's table, one row per BS month (the AD date of day 1, and its length), GENERATED
--     from bsCalendar.js — never typed — and bsMonthsSql.test.js asserts every row still equals what
--     bsToAd() returns, so the two copies cannot drift. It covers exactly the years the JS table does
--     (BS 2000–2087); a date outside it converts to NULL here, where the JS falls back to an
--     approximation. Reference data: readable by every signed-in account, written by migrations only.
--
-- (2) Decided with Aashish (2026-09-14): a gazetted PUBLIC holiday (Holiday Calendar, type public,
--     not removed) inside a leave range is not charged against the balance. Staff already get those
--     days paid under the Labour Act's 13 public holidays; charging leave for them took the day twice.
--     hr_leave_requests_validate derives `days` = calendar days − public holidays in the range, and
--     refuses a request with no working day left in it (including a half day on a holiday). Approval
--     marks those days Holiday on the attendance sheet, not leave. Rostered days off still count.
--     Existing pending and approved requests are recounted below; live on 2026-09-14 every employee is
--     monthly-paid, so marking a holiday Holiday rather than Paid Leave moves no one's pay.
--
-- (3) request_shift_swap refuses a day already past, a day not yet published, and a day that already
--     has an open swap request for either employee. The Staff app only shows published days, but the
--     function trusted whatever days it was sent.

CREATE TABLE IF NOT EXISTS public.bs_months (
  bs_year  int  NOT NULL,
  bs_month int  NOT NULL CHECK (bs_month BETWEEN 1 AND 12),
  ad_start date NOT NULL UNIQUE,
  days     int  NOT NULL CHECK (days BETWEEN 28 AND 32),
  PRIMARY KEY (bs_year, bs_month)
);
ALTER TABLE public.bs_months ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS bs_months_select ON public.bs_months;
CREATE POLICY bs_months_select ON public.bs_months FOR SELECT TO authenticated USING (true);
REVOKE ALL ON public.bs_months FROM anon, authenticated;
GRANT SELECT ON public.bs_months TO authenticated, service_role;

