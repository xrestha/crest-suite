'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { Store, homeDir, acquireLock, RotatingLog } = require('../src/store')
const { installStartup, startupInstalled, startupPaths, startupCmd } = require('../src/startup')
const { parseArgs } = require('../src/main')
const { tmpDir } = require('./support')

test('home folder: override, Windows APPDATA, ~/.config elsewhere', () => {
  assert.equal(homeDir({ CREST_PRINT_HELPER_HOME: '/x/y' }, 'win32'), '/x/y')
  assert.equal(homeDir({ APPDATA: 'C:\\Users\\Sita\\AppData\\Roaming' }, 'win32'), path.join('C:\\Users\\Sita\\AppData\\Roaming', 'CrestPrintHelper'))
  assert.equal(homeDir({ XDG_CONFIG_HOME: '/home/a/.config' }, 'linux'), '/home/a/.config/crest-print-helper')
})

test('config and state round-trip; clearing the pairing forgets both', () => {
  const s = new Store(tmpDir())
  assert.equal(s.loadConfig(), null)
  s.saveConfig({ deviceId: 'd', secret: 's', deviceName: 'PC', clientName: 'Outlet' })
  assert.equal(s.loadConfig().secret, 's')
  s.updateConfig({ deviceName: 'Kitchen PC' })
  assert.equal(s.loadConfig().deviceName, 'Kitchen PC')
  s.saveState({ pending: { printed: ['a'], failed: [{ id: 'b', reason: 'r' }] }, recent: [['a', 1]] })
  assert.deepEqual(s.loadState().pending.printed, ['a'])
  s.clearPairing()
  assert.equal(s.loadConfig(), null)
  assert.deepEqual(s.loadState().pending, { printed: [], failed: [] })
  fs.writeFileSync(s.configFile, '{ broken')
  assert.equal(s.loadConfig(), null)
})

test('single instance: a live lock blocks, a dead or pre-reboot lock is taken over', () => {
  const dir = tmpDir()
  const file = path.join(dir, 'helper.lock')
  const boot = 1_700_000_000_000
  const a = acquireLock(file, { pid: 111, boot, isAlive: () => true })
  assert.equal(a.ok, true)
  const b = acquireLock(file, { pid: 222, boot, isAlive: pid => pid === 111 })
  assert.deepEqual(b, { ok: false, pid: 111 })
  const c = acquireLock(file, { pid: 333, boot, isAlive: () => false })
  assert.equal(c.ok, true, 'the pid is gone: stale')
  assert.equal(JSON.parse(fs.readFileSync(file, 'utf8')).pid, 333)
  const d = acquireLock(file, { pid: 444, boot: boot + 3_600_000, isAlive: () => true })
  assert.equal(d.ok, true, 'written before the computer last started: stale even if the pid is reused')
  d.release()
  assert.equal(fs.existsSync(file), false)
})

test('the log rolls over at its size limit and keeps two old files', () => {
  const dir = tmpDir()
  const log = new RotatingLog(path.join(dir, 'helper.log'), { maxBytes: 300, keep: 2 })
  for (let i = 0; i < 40; i++) log.info(`line ${i} ${'x'.repeat(20)}`)
  const files = fs.readdirSync(dir).sort()
  assert.deepEqual(files, ['helper.log', 'helper.log.1', 'helper.log.2'])
  for (const f of files) assert.ok(fs.statSync(path.join(dir, f)).size <= 300)
  log.error('boom', new Error('stack here'))
  assert.match(fs.readFileSync(path.join(dir, 'helper.log'), 'utf8'), /ERROR boom\n {2}Error: stack here/)
})

test('start with Windows: copies the exe and writes a Startup .cmd that starts it minimized', () => {
  const root = tmpDir()
  const env = { LOCALAPPDATA: path.join(root, 'Local'), APPDATA: path.join(root, 'Roaming') }
  const exe = path.join(root, 'Downloads', 'CrestPrintHelper.exe')
  fs.mkdirSync(path.dirname(exe), { recursive: true })
  fs.writeFileSync(exe, 'MZ fake exe')
  assert.equal(startupInstalled(env, path), false)
  const paths = installStartup({ execPath: exe, env, p: path })
  assert.equal(fs.readFileSync(paths.exe, 'utf8'), 'MZ fake exe')
  assert.equal(paths.cmd, path.join(env.APPDATA, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup', 'Crest Print Helper.cmd'))
  const cmd = fs.readFileSync(paths.cmd, 'utf8')
  assert.equal(cmd, startupCmd())
  assert.match(cmd, /start "" \/min "%LOCALAPPDATA%\\CrestPrintHelper\\CrestPrintHelper\.exe"\r\n$/)
  assert.equal(startupInstalled(env, path), true)
  // Running from the installed copy: nothing to copy, the .cmd is rewritten.
  assert.doesNotThrow(() => installStartup({ execPath: paths.exe, env, p: path }))
  assert.equal(startupPaths({}, path), null)
})

test('command line flags', () => {
  assert.deepEqual(parseArgs(['--test-print', '192.168.1.50']).testPrint, { host: '192.168.1.50', port: 9100, width: 80 })
  assert.deepEqual(parseArgs(['--test-print', '10.0.0.9', '9101', '58']).testPrint, { host: '10.0.0.9', port: 9101, width: 58 })
  assert.match(parseArgs(['--test-print']).error, /needs the printer's address/)
  assert.match(parseArgs(['--test-print', '10.0.0.9', '9100', '72']).error, /80 or 58/)
  assert.equal(parseArgs(['--pair', '--no-startup']).pair, true)
  assert.equal(parseArgs(['--pair', '--no-startup']).noStartup, true)
  assert.equal(parseArgs(['--version']).version, true)
  assert.match(parseArgs(['--frobnicate']).error, /Unknown option/)
})
